import time
import logging
from ms_masa import MsMasaAgent

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class MarketMonitor:
    """Monitors Polymarket markets for price changes and signals."""

    def __init__(self, poll_interval: int = 60):
        self.agent = MsMasaAgent.from_env()
        self.poll_interval = poll_interval
        self.tracked_markets: dict[str, float] = {}  # market_id -> last_price

    def add_market(self, market_id: str):
        """Add a market to the watch list."""
        self.tracked_markets[market_id] = 0.0

    def check_markets(self) -> list[dict]:
        """Check all tracked markets for changes."""
        alerts = []
        for market_id, last_price in self.tracked_markets.items():
            try:
                analysis = self.agent.analyze_market(market_id)
                current_price = analysis["market"]["yes_price"]
                if last_price > 0:
                    change = current_price - last_price
                    if abs(change) > 0.02:  # 2% threshold
                        alerts.append({
                            "market_id": market_id,
                            "question": analysis["market"]["question"],
                            "price": current_price,
                            "change": change,
                            "signals": analysis.get("signals", []),
                        })
                self.tracked_markets[market_id] = current_price
            except Exception as e:
                logger.warning("Error checking %s: %s", market_id, e)
        return alerts

    def run(self):
        """Start the monitoring loop."""
        logger.info("Market Monitor starting with %d markets", len(self.tracked_markets))
        while True:
            alerts = self.check_markets()
            for alert in alerts:
                logger.info(
                    "ALERT: %s | Price: %.4f | Change: %+.4f",
                    alert["question"][:60], alert["price"], alert["change"],
                )
            time.sleep(self.poll_interval)


if __name__ == "__main__":
    monitor = MarketMonitor(poll_interval=60)
