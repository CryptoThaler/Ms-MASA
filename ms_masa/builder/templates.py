class LLMAnalyst:
    """Uses LLM reasoning to analyze Polymarket markets."""

    SYSTEM_PROMPT = """You are a prediction market analyst. Analyze the provided
market data and give a structured assessment. Focus on:
1. Market efficiency (is the price reflecting available information?)
2. Liquidity quality (can positions be entered/exited?)
3. Information signals (what does the order book structure suggest?)
4. Key risks and uncertainties

Be concise and data-driven. This is analytical only, not financial advice."""

    def __init__(self):
        self.agent = MsMasaAgent.from_env()
        self._client = None

    @property
    def llm(self):
        if self._client is None:
            import openai
            self._client = openai.OpenAI()
        return self._client

    def analyze(self, market_id: str) -> str:
        """Produce an LLM-powered analysis of a market."""
        data = self.agent.analyze_market(market_id)
        context = self.agent.get_agent_context("analytical_agent")
        user_msg = f"""Context:\\n{context}\\n\\nMarket Data:\\n{self.agent.compact_json(data)}\\n\\nProvide a structured analysis."""

