class SignalScanner:
    """Scans Polymarket for analytical signals across all markets."""

    def __init__(self):
        self.agent = MsMasaAgent.from_env()

    def full_scan(
        self,
        limit: int = 100,
        spread_threshold: float = 0.05,
        imbalance_threshold: float = 0.3,
    ) -> dict:
        """Run a full signal scan across tradeable markets."""
        signals = self.agent.detect_signals(
            limit=limit,
            spread_threshold=spread_threshold,
            imbalance_threshold=imbalance_threshold,
        )
        summary = {
            "markets_with_signals": len(signals),
            "total_signals": sum(len(s) for s in signals.values()),
            "by_type": {},
        }
        for sigs in signals.values():
            for s in sigs:
                sig_type = s["type"]
                summary["by_type"][sig_type] = summary["by_type"].get(sig_type, 0) + 1

        return {"summary": summary, "signals": signals}

    def scan_category(self, tag: str, limit: int = 50) -> list[dict]:
        """Scan a specific category for interesting markets."""
        markets = self.agent.scan_markets(tag=tag, limit=limit, sort_by="volume")
        interesting = [
            m for m in markets
            if m["certainty"] < 0.8 and m["volume"] > 1000
        ]
        return interesting


if __name__ == "__main__":
    scanner = SignalScanner()
    result = scanner.full_scan(limit=50)
    logger.info("Scan complete: %s", result["summary"])
