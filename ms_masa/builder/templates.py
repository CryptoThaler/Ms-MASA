class DataCollector:
    """Collects and stores Polymarket data for analysis."""

    def __init__(self, output_dir: str = "./data"):
        self.agent = MsMasaAgent.from_env()
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def snapshot_all_markets(self) -> str:
        """Take a snapshot of all tradeable markets."""
        markets = self.agent.scan_markets(limit=200, sort_by="volume")
        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        filename = f"markets_{timestamp}.json"
        path = self.output_dir / filename
        with open(path, "w") as f:
            json.dump({"timestamp": timestamp, "count": len(markets), "markets": markets}, f)
        logger.info("Saved %d markets to %s", len(markets), path)
        return str(path)

    def track_market_history(self, market_id: str, interval: int = 300, duration: int = 3600):
        """Track a single market over time."""
        history = []
        end_time = time.time() + duration
        while time.time() < end_time:
            try:
                analysis = self.agent.analyze_market(market_id)
                analysis["collected_at"] = datetime.utcnow().isoformat()
                history.append(analysis)
            except Exception as e:
                logger.warning("Collection error: %s", e)
            time.sleep(interval)

        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        path = self.output_dir / f"history_{market_id[:8]}_{timestamp}.json"
        with open(path, "w") as f:
            json.dump(history, f)
        logger.info("Saved %d snapshots to %s", len(history), path)
        return str(path)


if __name__ == "__main__":
    collector = DataCollector()
    collector.snapshot_all_markets()
